"""Generate src/pyunicode.rs: CPython's character classes as code point tables.

The redaction rules are Python `re` patterns over `str`, so `\\w`, `\\b`, `\\s`
and `\\d` mean what CPython's sre says for each code point, which differs from
the Rust `regex` crate's Unicode definitions (combining marks, `No` numerics,
U+001C..U+001F, ...). The tables are therefore generated from CPython itself.

Run with the interpreter the machine ships (Python 3.11, Unicode 14.0):

    uv run python crates/redactor/tools/gen_pyunicode.py > crates/redactor/src/pyunicode.rs
"""

import re
import sys
import unicodedata


def ranges(predicate):
    out = []
    start = None
    for cp in range(0x110000):
        ok = not (0xD800 <= cp <= 0xDFFF) and predicate(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, doc, table):
    print()
    print(f"/// {doc}")
    print(f"pub(crate) static {name}: &[(u32, u32)] = &[")
    for lo, hi in table:
        print(f"    (0x{lo:04X}, 0x{hi:04X}),")
    print("];")


def main():
    word = re.compile(r"\w")
    digit = re.compile(r"\d")
    space = re.compile(r"\s")

    # The hand-written classes in pychar.rs must agree with CPython; fail loudly
    # instead of emitting tables that quietly disagree with them.
    expected_space = [
        (0x09, 0x0D),
        (0x1C, 0x20),
        (0x85, 0x85),
        (0xA0, 0xA0),
        (0x1680, 0x1680),
        (0x2000, 0x200A),
        (0x2028, 0x2029),
        (0x202F, 0x202F),
        (0x205F, 0x205F),
        (0x3000, 0x3000),
    ]
    assert ranges(lambda c: space.match(c) is not None) == expected_space
    assert ranges(str.isspace) == expected_space
    folds = {
        letter: [
            cp
            for cp in range(0x110000)
            if not 0xD800 <= cp <= 0xDFFF and re.fullmatch("(?i)" + letter, chr(cp))
        ]
        for letter in "abcdefghijklmnopqrstuvwxyz"
    }
    extra = {"i": [0x130, 0x131], "k": [0x212A], "s": [0x17F]}
    for letter, cps in folds.items():
        assert cps == sorted([ord(letter.upper()), ord(letter)] + extra.get(letter, [])), letter

    print("// @generated by crates/redactor/tools/gen_pyunicode.py -- do not edit.")
    print(f"// CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.")
    emit(
        "WORD",
        "Code points CPython's `re` matches with `\\w` in a `str` pattern.",
        ranges(lambda c: word.match(c) is not None),
    )
    emit(
        "DECIMAL",
        "Code points CPython's `re` matches with `\\d` in a `str` pattern.",
        ranges(lambda c: digit.match(c) is not None),
    )
    emit(
        "PRINTABLE",
        "Code points for which CPython's `str.isprintable()` is true (what `repr()` leaves unescaped).",
        ranges(str.isprintable),
    )


if __name__ == "__main__":
    main()
