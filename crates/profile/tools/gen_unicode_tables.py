"""Write src/pyrepr/unicode_tables.rs: the code points CPython's repr() escapes.

`repr(str)` keeps a non-ASCII character as it is when `str.isprintable()` is
true for it and escapes it otherwise. That depends on the Unicode database the
interpreter was built with (Python 3.11: Unicode 14.0.0, the version Debian
bookworm ships), so the table is generated from CPython rather than from a Rust
crate that may follow a newer Unicode release.

Run from the repository root with the backend's interpreter:

    uv run python crates/profile/tools/gen_unicode_tables.py
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "pyrepr" / "unicode_tables.rs"


def ranges(predicate):
    out = []
    start = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            # Surrogates never occur in a Rust `str`; folding them into the
            # neighbouring range keeps the table short.
            hit = True
        else:
            hit = predicate(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    non_printable = ranges(lambda c: not c.isprintable())
    lines = [
        "// @generated by crates/profile/tools/gen_unicode_tables.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        "/// Inclusive ranges of the code points for which `str.isprintable()` is false.",
        "pub(crate) static NON_PRINTABLE: &[(u32, u32)] = &[",
    ]
    for start, end in non_printable:
        lines.append(f"    (0x{start:04X}, 0x{end:04X}),")
    lines.append("];")
    lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {len(non_printable)} ranges to {OUT}")


if __name__ == "__main__":
    main()
